type NavTo = '/' | '/library' | '/runs' | '/access' | '/audit' | '/system-design'
type NavItem = { to: NavTo; label: string; icon: React.ReactNode; exact?: boolean; adminOnly?: boolean }
type NavGroup = { label: string; items: NavItem[] }

