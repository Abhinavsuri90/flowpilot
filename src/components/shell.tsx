const ROLE_TONE = { admin: 'brand', member: 'flow', viewer: 'neutral' } as const

function useSignOut() {
  const queryClient = useQueryClient()
  const router = useRouter()
  return useMutation({
    mutationFn: () => api.post('/api/auth/logout'),
    onSettled: async () => {
      queryClient.clear()
      await router.invalidate()
      await router.navigate({ to: '/login', search: { redirect: undefined } })
    },
  })
}

function isActive(pathname: string, item: NavItem): boolean {
  if (item.exact) return pathname === item.to
  if (item.to === '/library') return pathname.startsWith('/library') || pathname.startsWith('/w/') || pathname.startsWith('/workflows/')
  return pathname === item.to || pathname.startsWith(item.to + '/')
}

function NewRecipeButton({ me, className, onNavigate }: { me: Me; className?: string; onNavigate?: () => void }) {
  if (canCreateInWorkspace(me.workspace?.role ?? null)) {
    return (
      <Link to="/workflows/new" onClick={onNavigate} className={buttonClass('brand', 'md', className)}>
        <Plus className="size-4" /> New recipe
      </Link>
    )
  }
  return (
    <Tip content="Viewers can run recipes but cannot create them" side="bottom">
      <Button variant="brand" disabled className={className} icon={<Plus className="size-4" />}>
        New recipe
      </Button>
    </Tip>
  )
}

